#!/usr/bin/env python3
"""Generate js/data.js from data/normalized_cities.json so the app runs from
file:// with no fetch/CORS issues. The JSON stays the single source of truth."""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / "data" / "normalized_cities.json").read_text())
out = "// GENERATED by tools/gen_data_js.py from data/normalized_cities.json — do not edit by hand.\n"
out += "window.CITY_DATA = " + json.dumps(data, indent=1) + ";\n"
(root / "js" / "data.js").write_text(out)
print("wrote js/data.js", len(out), "bytes")
